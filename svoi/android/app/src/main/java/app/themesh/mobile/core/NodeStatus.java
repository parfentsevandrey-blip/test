package app.themesh.mobile.core;

/** Что сейчас с узлом (программой themesh), которым владеет приложение. */
public enum NodeStatus {
    /** Служба ещё не запускалась. */
    IDLE,
    /** Процесс запускается, интерфейс ещё не отвечает. */
    STARTING,
    /** Интерфейс отвечает, узел проверен (handshake). */
    RUNNING,
    /** Не запустился или остановился сам; идёт пауза перед новой попыткой. */
    FAILED,
    /** Остановлен по просьбе человека («Выйти»). */
    STOPPED
}
