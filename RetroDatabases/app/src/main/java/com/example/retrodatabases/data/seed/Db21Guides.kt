            # elements are 2-bit polynomials: bit 0 is the constant term and bit 1 is the x term
            def gf4_mul(x, y):
                result = 0
                for bit in range(2):
                    if (y >> bit) & 1:
                        result ^= x << bit
                # reduce x squared to x plus 1, because x squared plus x plus 1 is zero
                if result & 4:
