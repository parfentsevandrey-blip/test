def norm(s):
    """Сравнение цифр без оглядки на вид пробела и дефиса."""
    return re.sub(r'[\s  ]+', ' ', str(s)).replace('−', '-').lower()


def check_link(sel, dropped, blocks):
    """Связка в обе стороны: ключевая цифра каждого отобранного факта обязана быть
    в прозе сектора, а факт, который движок не взял, в прозе появляться не должен —
    иначе отбор становится декорацией."""
    text = norm(' '.join(p for b in blocks for p in b['paras']))
    missing = [i for i in sel if norm(i['numbers'][0]) not in text]
    extra = [i for i in dropped if norm(i['numbers'][0]) in text]
    return missing, extra


def main():
    sys.path.insert(0, HERE)
    from picker import select

    os.makedirs(os.path.join(HERE, 'content'), exist_ok=True)
    os.makedirs(os.path.join(HERE, 'build'), exist_ok=True)
    json.dump({'window': [LO, HI], 'items': POOL},
              open(os.path.join(HERE, 'content', 'pool.json'), 'w', encoding='utf-8'),
              ensure_ascii=False, indent=1)

    issue = {
        'issue_line': 'Выпуск № 08 · 31 августа — 7 сентября 2026',
        'week_label': '31.08–07.09.2026',
        'prepared_by': 'NL Real Estate Research Desk',
        'imprint': 'Формат: MarketBeat · даты всех сюжетов проверены по странице источника',
        'sectors': [],
    }
    reports, missing, extra = {}, {}, {}
    for key in ORDER:
        items = [i for i in POOL if i['sector'] == key]
        sel, rep = select(items, PROSE_BUDGET, LO, HI)
        reports[key] = rep
        if not rep.get('ok'):
            continue
        sec = dict(SECTORS[key])
        sec['blocks'] = PROSE[key]
        sec['facts'] = [i['id'] for i in sel]
        issue['sectors'].append(sec)
        dropped = [i for i in items if i not in sel]
        missing[key], extra[key] = check_link(sel, dropped, PROSE[key])

    json.dump(issue, open(os.path.join(HERE, 'content', 'issue.json'), 'w', encoding='utf-8'),
              ensure_ascii=False, indent=1)
    json.dump(reports, open(os.path.join(HERE, 'build', 'select_report.json'), 'w',
                            encoding='utf-8'), ensure_ascii=False, indent=1)

    bad = 0
    print('ОТБОР')
    for k in ORDER:
        r = reports[k]
        if not r.get('ok'):
            print(f'  {SECTORS[k]["name"]:<22} НЕ СОБРАЛСЯ: {r["reason"]} {r.get("closest")}')
            bad += 1
            continue
        print(f'  {SECTORS[k]["name"]:<22} {r["selected"]} из {r["considered"]}, '
              f'бюджет {r["fill"]*100:.0f}%, блоки {r["by_block"]}, знаки {r["by_polarity"]}')
        drop = [d for d in r['dropped']]
        if drop:
            print('     не вошли: ' + '; '.join(f'{d["id"]} ({d["why"]})' for d in drop))
        if missing[k]:
            bad += 1
            print('     НЕТ В ПРОЗЕ: ' + ', '.join(
                f'{i["id"]} [{i["numbers"][0]}]' for i in missing[k]))
        if extra[k]:
            bad += 1
            print('     В ПРОЗЕ, НО НЕ ОТОБРАНО: ' + ', '.join(
                f'{i["id"]} [{i["numbers"][0]}]' for i in extra[k]))
    if bad:
        print('\nсвязка отбор -> проза нарушена')
        sys.exit(1)
    print('\nсвязка отбор -> проза: все отобранные факты присутствуют в тексте')


if __name__ == '__main__':
    main()
