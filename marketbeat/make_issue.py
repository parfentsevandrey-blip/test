def main():
    pool_path = os.path.join(HERE, 'content', 'pool.json')
    os.makedirs(os.path.dirname(pool_path), exist_ok=True)
    json.dump({'window': [LO, HI], 'items': POOL},
              open(pool_path, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)

    subprocess.run([sys.executable, os.path.join(HERE, 'measure.py'), pool_path],
                   check=True, cwd=HERE)
    pool = json.load(open(pool_path, encoding='utf-8'))

    sys.path.insert(0, HERE)
    from picker import select
    from build_mb import BODY_BUDGET_PX

    issue = {
        'issue_line': 'Выпуск № 08 · 31 августа — 7 сентября 2026',
        'week_label': '31.08–07.09.2026',
        'prepared_by': 'NL Real Estate Research Desk',
        'imprint': 'Формат: MarketBeat · все сюжеты проверены по дате на странице источника',
        'sectors': [],
    }
    reports = {}
    for key in ORDER:
        sec = dict(SECTORS[key])
        items = [i for i in pool['items'] if i['sector'] == key]
        # заголовки блоков занимают часть полосы — отдаём сюжетам остальное
        budget = BODY_BUDGET_PX - 2 * 34
        sel, rep = select(items, budget, LO, HI)
        reports[key] = rep
        sec['blocks'] = [
            dict(title=t, subtitle=s,
                 items=[i for i in sel if i['block'] == b])
            for b, (t, s) in zip(('investment', 'occupier'), sec['blocks'])]
        srcs = sorted({i['outlet'] for i in sel})
        sec['sources_line'] = 'Источники недели: ' + ', '.join(srcs)
        issue['sectors'].append(sec)

    out = os.path.join(HERE, 'content', 'issue.json')
    json.dump(issue, open(out, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    json.dump(reports, open(os.path.join(HERE, 'build', 'select_report.json'), 'w',
                            encoding='utf-8'), ensure_ascii=False, indent=1)

    print('\nОТБОР')
    for k in ORDER:
        r = reports[k]
        if not r.get('ok'):
            print(f'  {SECTORS[k]["name"]:<22} НЕ СОБРАЛСЯ: {r["reason"]}')
            continue
        print(f'  {SECTORS[k]["name"]:<22} {r["selected"]} из {r["considered"]}, '
              f'полоса заполнена на {r["fill"]*100:.0f}%, '
              f'блоки {r["by_block"]}, знаки {r["by_polarity"]}')
    return out


if __name__ == '__main__':
    main()
