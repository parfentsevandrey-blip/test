def series(points, mark, fmt=f1, every=6):
    """Точки линии: подпись месяца у каждой шестой, значение — у отмеченных."""
    return [dict(k=(k if i % every == 0 or i == len(points) - 1 else ''), v=v,
                 t=(fmt(v) if i in mark else ''))
            for i, (k, v) in enumerate(points)]


