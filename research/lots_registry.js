const short = u => u ? u.replace(/^https?:\/\//,'').replace(/^www\./,'').replace(/\/$/,'') : null;

/* короткая подпись для узкой колонки: площадка + номер объявления */
function label(u){
  if(!u) return '—';
  let m;
  if((m=u.match(/cian\.ru\/rent\/commercial\/(\d+)/)))  return 'ЦИАН '+m[1];
  if((m=u.match(/move\.ru\/objects\/(\d+)/)))           return 'move.ru '+m[1];
  if((m=u.match(/mirkvartir\.ru\/(\d+)/)))              return 'МирКвартир '+m[1];
  if((m=u.match(/realestate\.ru\/offer\/(\d+)/)))       return 'realestate '+m[1];
  if((m=u.match(/shopandmall\.ru\/offers\/.*?(\d+)$/))) return 'shopandmall '+m[1];
  if(u.includes('gladston'))  return 'gladston 42457';
  if(u.includes('arendator')) return 'arendator.ru';
  return short(u);
}

