const L = require("./doclib");
const { D, C, p, h1, h2, h3, lead, bullet, callout, table, figure, tcap, note, spacer } = L;
const data = require("./data.json");

const f1 = (x) => x.toFixed(1).replace(".", ",");
const f2 = (x) => x.toFixed(2).replace(".", ",");
const f0 = (x) => Math.round(x).toLocaleString("ru-RU").replace(/ /g, " ");
const city = (n) => data.main.find((r) => r.city === n) || data.ovt.find((r) => r.city === n);
const ov = (n) => data.ovt.find((r) => r.city === n);
const S = (n, k) => f1((100 * city(n).bin_counts[k]) / city(n).n);
const COV = (n) => f1(100 * city(n).coverage_ratio);
const MED = (n) => f0(city(n).median_m2);
const DEN = (n) => f0(city(n).density_per_builtup_km2);

// компактная таблица городов континента
const cityTable = (names, src) =>
  table(
    [{ t: "Город", w: 20, a: "l" }, { t: "Зданий", w: 13, a: "r" }, { t: "до 300", w: 11, a: "r" },
     { t: "300–1к", w: 11, a: "r" }, { t: "1к–10к", w: 11, a: "r" }, { t: ">10к", w: 9, a: "r" },
     { t: "Медиана, м²", w: 12, a: "r" }, { t: "Застр.", w: 13, a: "r" }],
    names.map((n) => {
      const r = src ? ov(n) : city(n);
      const q = (k) => f1((100 * r.bin_counts[k]) / r.n);
      return [{ v: n, b: true }, f0(r.n), q(0) + "%", q(1) + "%", q(2) + "%",
        f2((100 * r.bin_counts[3]) / r.n) + "%", f0(r.median_m2), f1(100 * r.coverage_ratio) + "%"];
    }),
    { size: 17 }
  );

