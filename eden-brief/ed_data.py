#
# Опубликованная цифра одна: старт продаж «от 1,1 млрд ₽ за резиденцию
# площадью около 250 кв. м». Делением получается 4,4 млн ₽ за метр, но это
# верхняя граница, а не средний метр по дому: формулировка описывает
# конкретный лот, а площадь в ней округлена. При 3,5 млн ₽ за метр те же
# 1,1 млрд соответствуют резиденции 314 м² — это ближе к реальному составу
# дома, где средняя площадь 282 м², а 18 квартир из 22 от четырёх комнат.
# Поэтому за базовую в справке принята оценка 3,5 млн ₽ за метр, а 4,4 млн
# показаны как верхняя граница диапазона.
ANCHOR_PRICE, ANCHOR_AREA = 1_100_000_000, 250.0   # опубликованный старт продаж
PPM_HI = ANCHOR_PRICE / ANCHOR_AREA                 # 4,4 млн ₽/м² — верхняя граница
PPM = 3_500_000                                     # базовая оценка метра
ANCHOR_AREA_AT_PPM = ANCHOR_PRICE / PPM             # какой лот стоит 1,1 млрд при 3,5
LIVING = 6_200                                      # м² жилья
N = 22
MONTHS_LEFT = 37                                    # август 2026 → III кв. 2029
BILLION_AREA = 1_000_000_000 / PPM                  # с какой площади резиденция дороже миллиарда

# Сколько резиденций дороже миллиарда — оценка, а не расчёт: поквартирных
# площадей застройщик не публикует, известны только диапазоны по типам.
# Порог — 285,7 м² при средней по дому 281,8 м². Лот 107,3 м² заведомо ниже;
# из трёх трёхкомнатных (224–288 м²) порог берёт в лучшем случае один;
# оставшиеся 18 квартир от четырёх комнат в среднем около 296 м², и порог
# проходит примерно половина из них. Итого ≈ 10 резиденций из 22.
BILLION_N = 10
DELUXE_TICKET = 476_000_000                         # средняя сделка делюкс, NF Group (437–515)

