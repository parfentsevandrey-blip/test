def peak(M):
    cum, low, pm = 0.0, 0.0, 0
    for r in M["base"]["rows"]:
        cum += r["equity"]
        if cum < low:
            low, pm = cum, r["m"]
    return -low, pm


def sale_room(M):
    """На сколько инвестор может снизить цену, пока мы не уходим в убыток."""
    return M["base"]["sale"] - M["rent"] / M["bids"]["12"]["bar_be"]


def bar_step(M, bar):
    return next(r for r in M["sens_bar"] if abs(r["bar"] - bar) < 1e-9)


def cand_row(name, M, terr):
    b = M["bids"]["12"]
    loss = M["at_ask"]["profit"]
    be = b["breakeven"] / M["ask"] - 1
    return [name, terr, eur(M["ask"]), ("прибыль " if loss >= 0 else "убыток ") + r100(abs(loss)),
            f"не нужно, запас {pct(be, 0)}" if be > 0 else "на " + pct(-be, 0),
            ("на " + pct(abs(b["m10"] / M["ask"] - 1), 0)) if b["m10"] < M["ask"] else "не нужно"]


