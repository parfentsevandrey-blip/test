def eur(v, digits=0):
    s = f"{abs(v):,.{digits}f}".replace(",", " ").replace(".", ",").replace(" ", ".")
    return ("−" if v < 0 else "") + "€ " + s


def r100(v):
    return eur(round(v / 100) * 100)


def tsd(v):
    return ("−" if v < 0 else "+") + f"{abs(v) / 1000:,.0f}".replace(",", ".")


def pct(v, digits=1):
    return "—" if v is None else f"{v * 100:.{digits}f} %".replace(".", ",").replace("-", "−")


