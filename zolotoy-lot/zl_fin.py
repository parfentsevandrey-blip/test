"""Отделка: поле Циан выверено вручную по текстам объявлений.

У Циан есть служебная колонка «Источник отделки». Где написано «из описания»,
значение получено эвристикой по тексту — и она ошибается систематически:
лот с прямой фразой «Квартиры без отделки» помечен «Дизайнерский», потому что
рядом стоит оборот «дизайнерские решения». В выборке по Софийской набережной
из 43 лотов сопоставимой базы метка «из описания» стоит у 13, и в 6 случаях
она противоречит тексту.

Группы:
  ready — можно заезжать: дизайнерский ремонт, отделка выполнена, с мебелью
  wb    — white box / «под чистовую»: нужна финишная отделка
  shell — бетон, без отделки, черновая, свободная планировка
"""

# url-хвост -> (группа, что написано в объявлении)
FIX = {
    # ── Софийский (апартаменты) ────────────────────────────────────────────
    '332212165': ('ready', 'выполнен дизайнерский ремонт, мебель Baxter, Minotti, Poltrona Frau'),
    '318593959': ('ready', 'апартамент с новой дизайнерской отделкой'),
    '318757099': ('ready', 'дизайнерская отделка'),
    '298881519': ('ready', 'в апартаменте выполнен ремонт в современном стиле'),
    '312710883': ('wb',    'квартира в отделке вайтбокс, под чистовую отделку'),
    '304329886': ('wb',    'отделка white box'),
    '312068074': ('shell', 'свободная планировка предполагает сделать квартиру своей мечты'),
    '332442882': ('shell', 'отделка в объявлении не заявлена, «срочная продажа»'),
    '330258418': ('shell', 'отделка в объявлении не заявлена'),
    # ── Дом Лаврушинский ───────────────────────────────────────────────────
    '329731850': ('shell', 'свободная планировка позволяет воплотить любые дизайнерские решения'),
    # ── Клубный дом Космо 4/22 ─────────────────────────────────────────────
    '330937338': ('shell', 'отделка в объявлении не заявлена'),
    '332200431': ('shell', 'резиденция без отделки'),
    # ── наш лот ────────────────────────────────────────────────────────────
    '326035617': ('ready', 'НАШ ЛОТ — премиум-ремонт сделан (решение заказчика)'),
}

# Лоты, исключённые из сопоставимой базы: это не одна квартира, а две,
# которые продаются вместе, и «площадь» в шапке — их сумма. Сравнивать
# такой лот с обычной квартирой 87,5 м² нельзя.
COMBO = {
    '331008023': '111 м² = две квартиры 59 + 51 м², корпус «Сад», продаются под объединение',
    '328655208': '111 м² = две квартиры 59 + 51 м², корпус «Сад», продаются под объединение',
}

SHELL = {'Без отделки', 'Черновая', 'Без ремонта'}
WB    = {'Предчистовая (white box)'}
READY = {'Чистовая', 'Дизайнерский', 'Евроремонт', 'Под ключ / с мебелью',
         'Косметический', 'С ремонтом (тип не указан)'}

key = lambda url: url.rstrip('/').rsplit('/', 1)[-1]

def grp(x):
    """Группа отделки лота с учётом ручной выверки."""
    f = FIX.get(key(x['url']))
    if f: return f[0]
    if x['fin'] in SHELL: return 'shell'
    if x['fin'] in WB:    return 'wb'
    if x['fin'] in READY: return 'ready'
    return 'shell'          # у застройщиков де-люкса «не указано» = бетон

combo = lambda x: key(x['url']) in COMBO

if __name__ == '__main__':
    import json, collections
    L = json.load(open('zl/zl_linked.json'))
    R = json.load(open('zl/zl_raw.json'))
    LO, HI = 65, 115
    band = [(n, x) for n, v in L.items() for x in v if LO <= x['area'] <= HI]
    print(f'сопоставимая база 65–115 м²: {len(band)} лотов до чистки, '
          f'{sum(1 for _, x in band if not combo(x))} после')
    print(' поле Циан   :', collections.Counter(x['fin'] or '—' for _, x in band).most_common())
    print(' после выверки:', collections.Counter(grp(x) for _, x in band if not combo(x)).most_common())
    src = {key(x['url']): x['finSrc'] for v in R.values() for x in v}
    hand = [x for _, x in band if key(x['url']) in FIX]
    print(f' выверено вручную: {len(hand)}; из них метка Циан стояла «из описания»: '
          f'{sum(1 for x in hand if src.get(key(x["url"])) == "из описания")}')
    print('\nгде метка Циан противоречит тексту объявления:')
    for n, x in sorted(band, key=lambda t: -t[1]['ppm']):
        f = FIX.get(key(x['url']))
        if not f: continue
        was = 'shell' if x['fin'] in SHELL else 'wb' if x['fin'] in WB else 'ready' if x['fin'] in READY else '—'
        if was != f[0] and was != '—':
            print(f'  ✗ {n:22s} {x["area"]:6.1f} м² {x["price"]/1e6:6.1f} млн  '
                  f'Циан «{x["fin"]}» → {f[0]:5s} ({f[1]})')
    print('\nисключены как составные лоты:')
    for _, x in band:
        if combo(x): print(f'  – {x["area"]:.1f} м² {x["price"]/1e6:.1f} млн — {COMBO[key(x["url"])]}')
