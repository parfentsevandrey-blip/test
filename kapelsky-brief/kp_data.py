def decor_mix(r):
    items = sorted(r['decor'].items(), key=lambda x: -x[1])
    return ' · '.join(f'{k} {v}' for k, v in items)


def deadline(r):
    if not r['deadline']:
        return '—'
    q = QUARTER.get(r['quarter'])
    return f"{q} кв. {r['deadline']}" if q else str(r['deadline'])


