QUARTER = {1: 'I', 2: 'II', 3: 'III', 4: 'IV',
           'first': 'I', 'second': 'II', 'third': 'III', 'fourth': 'IV'}
mln2 = lambda v: f'{v / 1e6:.2f}'.replace('.', ',')
