nf = lambda v: f'{v:,.0f}'.replace(',', ' ')
d1 = lambda v: f'{v:.1f}'.replace('.', ',')
pc = lambda v: f'{v:.1f}'.replace('.', ',') + ' %'

params, diag = [], []
for (name, addr, area, floor, fin, price, lo, hi), d in zip(LOTS, DIAG):
    d_lo, d_hi = (price - hi) / price, (price - lo) / price
    disc = '0' if d_lo == 0 else pc(d_lo * 100)
    params.append([
        name, addr, d1(area), floor, fin,
        d1(price / 1e6), nf(price / area),
        f'{nf(lo / 1e6)}–{nf(hi / 1e6)}' if lo != hi else nf(lo / 1e6),
        f'{nf(lo / area)}–{nf(hi / area)}',
        f'{disc}–{pc(d_hi * 100)}' if d_lo != d_hi else disc,
        f'{nf((price - hi) / 1e6)}–{nf((price - lo) / 1e6)}',
    ])
    diag.append([name] + d)

if __name__ == '__main__':
    json.dump({'params': params, 'diag': diag},
              open('sum/sum_tables.json', 'w'), ensure_ascii=False, indent=1)
    for r in params:
        print(f'{r[0]:26s} {r[2]:>6s} м²  эт.{r[3]:>6s}  {r[5]:>4s} млн  '
              f'{r[6]:>10s} ₽/м²  →  {r[7]:>9s} млн  ({r[9]})')
