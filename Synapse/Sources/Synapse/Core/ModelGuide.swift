    /// Когда семейство не узнали: собираем описание из тегов, размера и устройства.
    private static func generic(_ c: ModelCard) -> ModelGuide {
        let kind = c.tags.contains(.code) ? "модель для программирования"
            : c.tags.contains(.reasoning) ? "модель с рассуждениями" : "универсальная модель"
        var strengths = ["Работает полностью на вашем Mac, без интернета"]
        if c.tags.contains(.code) { strengths.append("Пишет, объясняет и исправляет код") }
        if c.tags.contains(.reasoning) { strengths.append("Умеет рассуждать перед ответом — меньше ошибок в логике") }
        if c.tags.contains(.agent) { strengths.append("Умеет вызывать инструменты") }
        if c.tags.contains(.multilingual) { strengths.append("Хорошо знает русский и другие языки") }
        if c.tags.contains(.small) { strengths.append("Небольшая — отвечает быстро даже на слабом Mac") }

        var weaknesses = ["Подробного описания от авторов в каталоге нет — качество лучше проверить на своих задачах"]
        if !c.tags.contains(.multilingual) { weaknesses.append("Качество русского заранее неизвестно — задайте пару вопросов для проверки") }

        var bestFor: [String] = []
        if c.tags.contains(.code) { bestFor.append("Программирование") }
        if c.tags.contains(.reasoning) { bestFor.append("Задачи на логику и математику") }
        if c.tags.contains(.vision) { bestFor.append("Вопросы по фото, скриншотам и документам") }
        if bestFor.isEmpty { bestFor.append("Общение, вопросы, тексты") }
        bestFor.append("Попробовать модель, которой нет среди отобранных")

        return family(c,
            "\(c.name) — \(kind) от \(c.lab) размером \(num(c.params)) млрд параметров (\(c.sizeClass.lowercased())). Это модель из живого каталога Hugging Face: её автор не дал описания, которое мы смогли бы проверить, поэтому здесь — то, что известно по её устройству.",
            strengths, weaknesses, bestFor, [])
    }

