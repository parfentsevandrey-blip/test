    /// Описание по семейству: к текстам семейства добавляются размер, смесь экспертов, зрение и факты карточки.
    private static func family(_ c: ModelCard, _ purpose: String, _ strengths: [String], _ weaknesses: [String],
                               _ bestFor: [String], _ facts: [String]) -> ModelGuide {
        var plus = strengths
        if let a = c.activeParams { plus.append("Смесь экспертов: на каждое слово работает около \(num(a)) млрд параметров из \(num(c.params)) — быстрее, чем можно ждать от такого размера") }
        if c.tags.contains(.vision) { plus.append("Видит изображения: фото, скриншоты, документы, графики") }
        var minus = weaknesses
        if let note = sizeNote(c) { minus.append(note) }
        return ModelGuide(purpose: purpose, strengths: Array(plus.prefix(5)), weaknesses: Array(minus.prefix(3)),
                          bestFor: Array(bestFor.prefix(4)), facts: facts + cardFacts(c))
    }

    /// Факты из карточки: разработчик, устройство, контекст, зрение, лицензия, дата.
    private static func cardFacts(_ c: ModelCard) -> [String] {
        var out = ["Разработчик: \(c.lab)", archText(c)]
        if let n = c.contextLength, n > 0 { out.append(contextText(n)) }
        if c.tags.contains(.vision) { out.append("Видит изображения") }
        if let l = c.license, !l.isEmpty { out.append(licenseText(l)) }
        if let d = c.created, let when = monthYear(d) { out.append("Сборка опубликована на Hugging Face: \(when)") }
        return out
    }

    private static func archText(_ c: ModelCard) -> String {
        if let a = c.activeParams {
            return "Смесь экспертов (MoE): внутри много «специалистов», и на каждое слово включаются лишь нужные. Всего \(num(c.params)) млрд параметров, активно около \(num(a)) млрд"
        }
        return "Плотная модель: на каждое слово работают все \(num(c.params)) млрд параметров"
    }

    private static func contextText(_ n: Int) -> String {
        let amount = n >= 1_000_000 ? "\(num(Double(n) / 1_048_576)) млн" : "\(n / 1024) тыс."
        let pages = n / 600 / 10 * 10
        let tail = pages >= 10 ? " — это примерно \(pages) страниц текста" : ""
        return "Контекст (сколько текста модель держит в голове за раз) — до \(amount) токенов\(tail)"
    }

    private static func licenseText(_ l: String) -> String {
        let x = l.lowercased()
        if x == "apache-2.0" { return "Лицензия Apache 2.0 — можно свободно использовать, в том числе в работе" }
        if x == "mit" { return "Лицензия MIT — можно свободно использовать, в том числе в работе" }
        if x.hasPrefix("llama") { return "Лицензия Meta Llama — бесплатно, но с условиями Meta" }
        if x == "gemma" { return "Лицензия Gemma Terms of Use — бесплатно, с правилами допустимого использования" }
        if x.hasPrefix("cc-by-nc") { return "Лицензия \(l) — только некоммерческое использование" }
        if x == "other" || x == "unknown" { return "Особая лицензия — условия смотрите на странице модели" }
        return "Лицензия: \(l)"
    }

    private static func sizeNote(_ c: ModelCard) -> String? {
        if c.params < 2 { return "Очень маленькая: часто ошибается в фактах и теряет нить в сложных задачах — это плата за скорость" }
        if c.params < 5 { return "Небольшая: для сложного анализа и точных фактов лучше взять модель покрупнее" }
        if c.params >= 60 { return "Очень большая: нужен Mac с большим объёмом памяти (от 64 ГБ)" }
        return nil
    }

    private static let months = ["январь", "февраль", "март", "апрель", "май", "июнь",
                                 "июль", "август", "сентябрь", "октябрь", "ноябрь", "декабрь"]

    private static func monthYear(_ d: Date) -> String? {
        var cal = Calendar(identifier: .gregorian)
        cal.timeZone = TimeZone(identifier: "UTC") ?? cal.timeZone
        let parts = cal.dateComponents([.year, .month], from: d)
        guard let y = parts.year, let m = parts.month, (1...12).contains(m) else { return nil }
        return "\(months[m - 1]) \(y)"
    }

    /// 0,8 · 3,6 · 27 — без локали, с запятой.
    private static func num(_ x: Double) -> String {
        let s = x < 10 ? String(format: "%.1f", x) : String(format: "%.0f", x)
        return (s.hasSuffix(".0") ? String(s.dropLast(2)) : s).replacingOccurrences(of: ".", with: ",")
    }

    /// «-unsloth-qwen3.5-9b-gguf-qwen3.5-9b-qwen-qwen3.5-9b-»: разделители приведены к дефису.
    private static func haystack(_ c: ModelCard) -> String {
        let raw = [c.id, c.name, c.baseModel ?? ""].joined(separator: " ").lowercased()
        let dashed = raw.replacingOccurrences(of: "/", with: "-")
            .replacingOccurrences(of: "_", with: "-")
            .replacingOccurrences(of: " ", with: "-")
        return "-" + dashed + "-"
    }

    private static func matches(_ keys: [String], _ hay: String) -> Bool {
        keys.contains { key in
            key.split(separator: " ").allSatisfy { hay.range(of: String($0)) != nil }
        }
    }
