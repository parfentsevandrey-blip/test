"""«Что можно купить за те же деньги» — таблица и фотокарточки из одного списка.

Наш лот в бетоне, поэтому в сравнение он входит по цене «под ключ»:
57,0 млн ₽ + 79,5 м² × 150 тыс. ₽/м² = 68,9 млн ₽.
Циан даёт цены по проектам выгрузок, Яндекс Недвижимость — фото готовых
ремонтов (Циан отдаёт 403 на автоматические запросы).
"""
import json

nf = lambda v: f'{v:,.0f}'.replace(',', ' ')
mn = lambda v: f'{v / 1e6:.1f}'.replace('.', ',')
Y = 'https://realty.yandex.ru/offer/%s/'
C = 'https://www.cian.ru/sale/flat/%s/'
FIT, OUR_A, OUR_P = 150_000, 79.5, 56_999_999
OUR_KEY = OUR_P + OUR_A * FIT

#  название, квартира, отделка, цена ₽, площадь м², ссылка, подпись, фото
LOTS = [
    ('▶ Наш лот «под ключ»', '79,5 м², эт. 15/19', 'бетон + ремонт', OUR_KEY, OUR_A,
     C % '331215568', 'Циан →', None),
    ('ЖК Lunar', '74,2 м², эт. 9/17', 'Дизайнерский', 86_000_000, 74.2,
     C % '329640617', 'Циан →', None),
    ('Новочерёмушкинская, 17', '65,0 м², эт. 19/20', 'Под ключ, с мебелью', 65_000_000, 65.0,
     C % '331624688', 'Циан →', None),
    ('ЖК «Новые Черемушки»', '95,3 м², эт. 5/36', 'Дизайнерский', 63_000_000, 95.3,
     Y % '6799954518334002630', 'Яндекс →', 'p1.jpg'),
    ('Академика Пилюгина, 4', '96,1 м², эт. 10/17', 'Евроремонт', 51_400_000, 96.1,
     Y % '2378280296864712388', 'Яндекс →', 'p4.jpg'),
    ('ЖК «Левел Академическая»', '70,8 м², эт. 13/19', 'бетон', 50_000_000, 70.8,
     C % '330076957', 'Циан →', None),
    ('ЖК «Дирижабль», Профсоюзная, 64', '80,0 м², эт. 23/40', 'Евроремонт', 48_000_000, 80.0,
     Y % '7567122433413726274', 'Яндекс →', 'p3.jpg'),
    ('ЖК «Новые Черемушки»', '81,6 м², эт. 4/36', 'Евроремонт', 45_000_000, 81.6,
     Y % '3938452234512302179', 'Яндекс →', 'p2.jpg'),
    ('ЖК «Файв Тауэрс»', '79,8 м², эт. 22/73', 'White box', 43_000_000, 79.8,
     C % '331942246', 'Циан →', None),
    ('Новочерёмушкинская, 8', '78,7 м², эт. 14/14', 'Евроремонт', 42_400_000, 78.7,
     Y % '6799954518309100246', 'Яндекс →', 'p5.jpg'),
    ('Вавилова, 52к1', '63,0 м², эт. 7/11', 'Дизайнерский', 41_500_000, 63.0,
     Y % '6239246392512496445', 'Яндекс →', 'p6.jpg'),
]

OUR, rest = LOTS[0], sorted(LOTS[1:], key=lambda x: -x[3])
rows = [[n, q, f, mn(p), nf(p / a), {'text': t, 'link': u}]
        for n, q, f, p, a, u, t, _ in [OUR] + rest]

cards = [{'img': img, 'title': n, 'spec': f'{q} · {f.lower()}',
          'price': f'{mn(p)} млн ₽', 'ppm': f'{nf(p / a)} ₽/м²', 'url': u, 'our': False}
         for n, q, f, p, a, u, t, img in LOTS if img]

# «Причина 3»: что покупатель получает готовым вместо нашего бетона
READY = {'Дизайнерский', 'Евроремонт', 'Под ключ, с мебелью'}
sg = lambda v, u: ('+' if v > 0 else '−') + f'{abs(v):.1f}'.replace('.', ',') + ' ' + u
city = [['▶ Наш лот «под ключ»', '79,5', '15/19', mn(OUR_KEY), '—', {'text': 'Циан →', 'link': C % '331215568'}]]
for n, q, f, p, a_, u, t, _ in sorted([x for x in LOTS[1:] if x[2] in READY], key=lambda x: -x[3]):
    city.append([f'{n} · {f.lower()}', f'{a_:.1f}'.replace('.', ','), q.split('эт. ')[1], mn(p),
                 f'{sg(a_ - OUR_A, "м²")} · {sg((p - OUR_KEY) / 1e6, "млн ₽")}', {'text': t, 'link': u}])

K = json.load(open('lev/lv_tables.json'))
K['alt'], K['photos'], K['ourKey'], K['city'] = rows, cards, OUR_KEY, city
json.dump(K, open('lev/lv_tables.json', 'w'), ensure_ascii=False, indent=1)
for r in rows: print(' | '.join(str(c if not isinstance(c, dict) else c['text']) for c in r))
print()
for r in city: print(' | '.join(str(c if not isinstance(c, dict) else c['text']) for c in r))
