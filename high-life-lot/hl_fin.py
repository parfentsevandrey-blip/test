# Лоты, исключённые из сопоставимой базы: по формату предложения они
# не конкурируют с нашим лотом и искажают сравнение.
EXCLUDE_CMP = {'332228194', '332228192', '329605453', '331598290',
               '327696691', '324705609'}

SHELL = {'Без отделки', 'Черновая', 'Без ремонта'}
WB    = {'Предчистовая (white box)'}
READY = {'Чистовая', 'Дизайнерский', 'Евроремонт', 'Под ключ / с мебелью',
         'Косметический', 'С ремонтом (тип не указан)'}

def key(url):
    return url.rstrip('/').rsplit('/', 1)[-1]

def level(x):
    """Что именно готово: мебель и техника или только отделка."""
    return FURNISHED.get(key(x['url']))

cmp_ok = lambda x: key(x['url']) not in EXCLUDE_CMP

def grp(x):
    """Группа отделки лота с учётом ручной выверки."""
    f = FIX.get(key(x['url']))
    if f: return f[0]
    if x['fin'] in SHELL: return 'shell'
    if x['fin'] in WB:    return 'wb'
    if x['fin'] in READY: return 'ready'
    return 'unk'

if __name__ == '__main__':
    import json, collections
    L = json.load(open('hl/hl_linked.json'))
    band = [x for x in L['HIGH LIFE'] if 110 <= x['area'] <= 140]
    print(f'сопоставимая база HIGH LIFE 110–140 м²: {len(band)} лотов')
    print(' поле Циан :', collections.Counter(x['fin'] or '—' for x in band).most_common())
    print(' после выверки:', collections.Counter(grp(x) for x in band).most_common())
    print(f' исправлено вручную: {sum(1 for x in band if key(x["url"]) in FIX)} лотов')
