"""Сравнение проектов локации: класс, срок, застройщик, отделка, объём экспозиции.

Класс, сроки и паркинг — сайты застройщиков и профильные порталы.
Прочерк в паркинге означает, что число машиномест не опубликовано.
"""
import json, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from hl_fin import grp

L = json.load(open('hl/hl_linked.json'))

META = {  # класс, срок сдачи, застройщик, адрес, машиномест
    'HIGH LIFE':             ('премиум', 'К1–К3 сданы, К4–К6 — IV кв. 2027', 'ГК «Пионер»',   'Летниковская, 11',      '750'),
    'Монблан':               ('элит',    'строится',                          'Галс-Девелопмент', 'Шлюзовая наб., 2',   '267'),
    'Клубный дом ОПУС':      ('элит',    'строится',                          'ГК «Пионер»',   'Дербеневская, 1',       '301'),
    'Эра':                   ('премиум', 'строится',                          'ТЕКТА ГРУПП',   'Дербеневская наб.',     '443'),
    'ЖК «А»':                ('бизнес',  'строится',                          'Брусника',      'Даниловский',           '189'),
    'ЛОТ от Аквилон':        ('бизнес',  'строится',                          'Группа Аквилон', 'Жуков пр-д',           'многоур.'),
    'Воксхолл':              ('бизнес',  'сдан в 2025–2026',                  'Группа «Эталон»', 'Летниковская',        '596'),
    'Левел Павелецкая Сити': ('бизнес',  'сдан в 2023–2025',                  'Level Group',   'Кожевнический пр-д',    '—'),
    'Павелецкая от Гранель': ('бизнес',  'строится',                          'ГК «Гранель»',  'Летниковская',          '90'),
    'Стремянный 2':          ('бизнес',  'сдан в 2024',                       'вторичный рынок', 'Стремянный пер., 2',  '—'),
    'Левел Павелецкая':      ('бизнес',  'сдан в 2019',                       'вторичный рынок', 'Жуков пр-д, 21Б',     '—'),
}
ORDER = ['HIGH LIFE', 'Монблан', 'Клубный дом ОПУС', 'Эра', 'ЖК «А»', 'ЛОТ от Аквилон',
         'Воксхолл', 'Левел Павелецкая Сити', 'Павелецкая от Гранель',
         'Стремянный 2', 'Левел Павелецкая']

SHORT = {'Клубный дом ОПУС': 'Кл. дом ОПУС', 'Левел Павелецкая Сити': 'Левел Пав. Сити',
         'Павелецкая от Гранель': 'Пав. от Гранель', 'Левел Павелецкая': 'Левел Павелецкая'}
# Плитки «сколько метров даёт бюджет» — только там, где квартиры 110–140 м²
# вообще есть в продаже; в трёх проектах их нет, и цифра была бы фикцией.
HAS_BAND = ['HIGH LIFE', 'Монблан', 'Клубный дом ОПУС', 'Эра',
            'ЖК «А»', 'ЛОТ от Аквилон', 'Воксхолл', 'Левел Павелецкая Сити']

nf  = lambda v: f'{v:,.0f}'.replace(',', ' ')
rng = lambda vs: f'{min(vs):.0f}–{nf(max(vs))}'
BUDGET = 96_000_000

rows, power = [], []
for name in ORDER:
    v = L[name]
    cls, due, dev, addr, park = META[name]
    rd = sum(1 for x in v if grp(x) in ('ready', 'wb'))
    if rd / len(v) > 0.5:  fin = 'в основном готовые'
    elif rd:               fin = f'{round(rd / len(v) * 100)} % готовых'
    else:                  fin = 'вся экспозиция в бетоне'
    ppm = sum(x['price'] for x in v) / sum(x['area'] for x in v)
    rows.append([name, cls, due, fin, str(len(v)),
                 rng([x['area'] for x in v]), rng([x['price'] / 1e6 for x in v]), nf(ppm)])
    if name in HAS_BAND: power.append([f'{BUDGET / ppm:.0f} м²', SHORT.get(name, name)])

K = json.load(open('hl/hl_tables.json'))
K['proj'], K['power'], K['projMeta'] = rows, power, {n: META[n] for n in ORDER}
json.dump(K, open('hl/hl_tables.json', 'w'), ensure_ascii=False, indent=1)
for r in rows: print(' | '.join(r))
print('\nбюджет', f'{BUDGET / 1e6:.0f} млн ₽ →', [f'{p[0]} {p[1]}' for p in power])
