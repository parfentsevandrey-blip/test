# ── сколько стоит отсрочка ─────────────────────────────────────────────────
def defer(share, months):
    """Экономический эквивалент беспроцентной отсрочки, ₽ и % от цены."""
    v = OUR_PRICE * share * MONEY * months / 12
    return v, v / OUR_PRICE

d11, p11 = defer(0.70, 11)      # рассрочка №1, сданная 1 очередь
d15, p15 = defer(0.70, 15)      # рассрочка №3/№4, 2 очередь

# ── чем на самом деле торгует застройщик в нашем размере ───────────────────
L = json.load(open('hl/hl_linked.json'))
HL = L['HIGH LIFE']
band = [x for x in HL if 110 <= x['area'] <= 140 and cmp_ok(x)]
dev2 = [x for x in band if x['corp'] and x['corp'] not in READY_CORP
        and x['seller'] == 'Застройщик' and grp(x) == 'shell' and x['ppm'] < 1_000_000]
w2 = sum(x['price'] for x in dev2) / sum(x['area'] for x in dev2)
key2 = w2 + FIT                 # приведено к «заехать можно»
eff2 = key2 * (1 - p15)         # с учётом бесплатной отсрочки на 15 месяцев
our_ppm = OUR_PRICE / OUR_AREA

