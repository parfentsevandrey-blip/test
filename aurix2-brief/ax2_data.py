ROOMS = {1: '1-комн.', 2: '2-комн.', 3: '3-комн.', 4: '4-комн.', 5: '5-комн.'}


def price_rows(project):
    g = sorted([x for x in LOTS if x['project'] == project], key=lambda x: x['area'])
    return [[d1(x['area']), ROOMS.get(x['rooms'], str(x['rooms'])), nf(x['price']),
             nf(x['ppm']), f"{x['floor']} из {x['floors']}",
             {'text': f"№ {x['number']}", 'link': x['url']}] for x in g]


def stats(project):
    g = [x for x in LOTS if x['project'] == project]
    return {
        'n': len(g),
        'areaLo': min(x['area'] for x in g), 'areaHi': max(x['area'] for x in g),
        'priceLo': min(x['price'] for x in g), 'priceHi': max(x['price'] for x in g),
        'ppmLo': min(x['ppm'] for x in g), 'ppmHi': max(x['ppm'] for x in g),
        'ppmW': sum(x['price'] for x in g) / sum(x['area'] for x in g),
        'sum': sum(x['price'] for x in g),
        'rooms': dict(collections.Counter(x['rooms'] for x in g)),
        'floors': sorted({x['floor'] for x in g}),
    }


def cards(project):
    """Карточки лотов: планировка + подписи, в порядке возрастания площади."""
    g = sorted([x for x in LOTS if x['project'] == project], key=lambda x: x['area'])
    return [{'file': x.get('planFile', ''), 'number': x['number'],
             'rooms': ROOMS.get(x['rooms'], ''), 'area': d1(x['area']),
             'floor': f"{x['floor']} из {x['floors']}", 'building': x['building'],
             'price': nf(x['price']), 'ppm': nf(x['ppm']), 'url': x['url']} for x in g]


