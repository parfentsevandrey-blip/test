"""Машиноместа в объявлениях аналогов: кто отдаёт м/м вместе с квартирой, кто продаёт отдельно и почём.

Классы проставлены вручную по прочитанным фрагментам описаний (flat-data/parking_mentions.json, offers.json);
остальные объявления — автоматически: «паркинг в доме» или «нет упоминания».
"""
import re

INCLUDED = {
    333439353: 'машиноместо входит в стоимость',
    334826500: 'машиноместо на 2 авто включено, отдельно не продаётся',
    276866719: '1 машиноместо включено в стоимость',
    310308101: 'парковочное место включено',
    328051132: 'машиноместо в подарок (акция «до конца августа»)',
}
SEPARATE_PRICE = {
    328840794: ('2 м/м по 15 млн', 15),
    332259534: ('2 м/м по 10 млн', 10),
    334508899: ('2 м/м по 10 млн', 10),
    331400693: ('2 м/м по 10–15 млн', 10),
    334521641: ('2 м/м по 10 млн', 10),
    333954503: ('2 м/м по 10 млн, вместе 155 млн', 10),
    334463550: ('2 м/м по 6 млн', 6),
    330768833: ('м/м и кладовая +5 млн', 5),
}
SEPARATE = {331799204, 334028747, 334194168, 334545837, 332370308, 333059415, 325815541, 334160139, 334912861,
            325143976, 326130429, 326127218, 334849838, 334151483, 327795980, 334311989, 334900595, 333995352,
            326296744, 332873001, 332403870, 327191560, 324701119, 322358986, 334093076, 329819607}
HAS_SPOT = {334501838, 327478113, 331746600, 322444477, 332420596, 332120247, 333356838, 331284749, 334021525,
            324447008, 332129819, 331735375}
RANK = ['включено', 'отдельно, цена указана', 'продаётся отдельно', 'есть м/м, условия не указаны', 'паркинг в доме',
        'нет упоминания']
GENERIC = re.compile(r'паркинг|парковк|машиномест|машино-мест', re.I)


def classify(cid, description):
    if cid in INCLUDED:
        return 'включено', INCLUDED[cid]
    if cid in SEPARATE_PRICE:
        return 'отдельно, цена указана', SEPARATE_PRICE[cid][0]
    if cid in SEPARATE:
        return 'продаётся отдельно', None
    if cid in HAS_SPOT:
        return 'есть м/м, условия не указаны', None
    if GENERIC.search(description or ''):
        return 'паркинг в доме', None
    return 'нет упоминания', None


def best(items):
    """Из нескольких объявлений одной квартиры берём самое информативное упоминание."""
    return min(items, key=lambda t: RANK.index(t[0]))
