def n(v, d=0):
    if v is None:
        return '—'
    s = f'{v:,.{d}f}'.replace(',', ' ').replace('.', ',')
    return s


def mln(v):
    return n(v / 1e6, 1) + ' млн ₽'


def e(s):
    return html.escape(str(s or ''))


