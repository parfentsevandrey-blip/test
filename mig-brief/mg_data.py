# ── чем различаются стройки вокруг ──────────────────────────────────────────
def _detail(name, stage='строится'):
    ls = [l for l in _coh
          if (l.get('complex') or '') == name
          and (('строится' if l.get('houseFinished') is False else 'готов') == stage)]
    if not ls:
        return None
    dec = {}
    for l in ls:
        k = l.get('decoration') or l.get('decorFilter') or 'не указана'
        dec[k] = dec.get(k, 0) + 1
    DEC = {'without': 'без отделки', 'fine': 'чистовая', 'preFine': 'предчистовая',
           'rough': 'черновая', 'fineWithFurniture': 'под ключ'}
    top = max(dec, key=dec.get)
    dl = next((l['deadline'] for l in ls if l.get('deadline')), None)
    return [SHORT.get(name, name),
            f"{max(l.get('floors') or 0 for l in ls)}",
            f"{QUARTER[dl['quarter']]} кв. {dl['year']}" if dl and dl.get('quarter') else '—',
            DEC.get(top, top), str(len(ls)),
            f"{med([l['totalArea'] for l in ls]):.0f}",
            nf(round(med([l['ppm'] for l in ls])))]


