def load(name):
    d = json.load(open(os.path.join(HERE, name + '.json'), encoding='utf-8'))
    out = []
    for l in d['lots']:
        if not (l.get('priceRub') and l.get('totalArea') and l.get('lat')):
            continue
        l['ppm'] = l['priceRub'] / l['totalArea']
        l['dist'] = dist(SITE, (l['lat'], l['lng']))
        out.append(l)
    return d, out


