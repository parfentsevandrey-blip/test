// ─── helpers ─────────────────────────────────────────────────────────────
const bottomRule = (size = 6, color = RULE) => ({
  bottom: { style: BorderStyle.SINGLE, size, color, space: 6 },
});

function h1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    spacing: { before: 0, after: 160 },
    children: [new TextRun({ text, bold: true, size: 40, color: INK, font: 'Calibri' })],
  });
}
function h2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    spacing: { before: 380, after: 60 },
    border: bottomRule(),
    children: [new TextRun({ text, bold: true, size: 28, color: INK, font: 'Calibri' })],
  });
}
function h3(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_3,
    spacing: { before: 260, after: 100 },
    children: [new TextRun({ text, bold: true, size: 24, color: INK, font: 'Calibri' })],
  });
}
function timing(text) {
  return new Paragraph({
    spacing: { before: 40, after: 140 },
    children: [new TextRun({ text, size: 18, color: RED, bold: true, allCaps: true, font: 'Calibri' })],
  });
}
// speech body — runs: string | {b:'...'} for bold
function say(runs) {
  const arr = (Array.isArray(runs) ? runs : [runs]).map(r =>
    typeof r === 'string'
      ? new TextRun({ text: r, size: 24, font: 'Calibri' })
      : new TextRun({ text: r.b, size: 24, bold: true, font: 'Calibri' }));
  return new Paragraph({ spacing: { after: 140, line: 320 }, children: arr });
}
function note(text) {
  return new Paragraph({
    spacing: { before: 100, after: 200, line: 280 },
    indent: { left: 280 },
    border: { left: { style: BorderStyle.SINGLE, size: 12, color: RULE, space: 10 } },
    children: [new TextRun({ text, size: 20, italics: true, color: GREY, font: 'Calibri' })],
  });
}
function plain(text, opts = {}) {
  return new Paragraph({
    spacing: { after: opts.after ?? 140, line: 300 },
    children: [new TextRun({ text, size: opts.size ?? 22, color: opts.color ?? INK, italics: !!opts.i, font: 'Calibri' })],
  });
}
function qa(q, a) {
  return [
    new Paragraph({
      spacing: { before: 200, after: 60, line: 300 },
      children: [new TextRun({ text: q, size: 22, bold: true, color: INK, font: 'Calibri' })],
    }),
    new Paragraph({
      spacing: { after: 120, line: 300 },
      children: [new TextRun({ text: a, size: 22, font: 'Calibri' })],
    }),
  ];
}

